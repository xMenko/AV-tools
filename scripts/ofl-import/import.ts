/**
 * Generates public/fixtures.json from the Open Fixture Library (MIT).
 *
 *   npm run ofl:import                     # pinned commit below, fetched with git into a temp dir
 *   npm run ofl:import -- --source <dir>   # existing OFL checkout (must contain fixtures/)
 *   npm run ofl:import -- --commit <sha>   # other commit (then update OFL_COMMIT below)
 *
 * Only reads JSON files from the OFL repository – no OFL code is executed. Runs at development time,
 * never in the app. Needs Node with TypeScript type stripping (≥ 22.18) and git.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { buildDatabase, type OflFixture, type OflRedirect } from '../../src/lib/core/dmx/ofl.ts';

/** Pinned OFL version. Update deliberately; the diff of public/fixtures.json shows what changed. */
const OFL_COMMIT = '174eae531a4cc15fc755835b2fdf265cc203651b';
const OFL_REPO = 'https://github.com/OpenLightingProject/open-fixture-library.git';
const OUT = resolve(import.meta.dirname, '../../public/fixtures.json');
const LICENSE_OUT = resolve(import.meta.dirname, '../../public/licenses/open-fixture-library.txt');
const INFO_OUT = resolve(import.meta.dirname, '../../src/lib/core/dmx/fixtureDbInfo.generated.ts');

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const git = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }).trim();

let dir = arg('--source');
let tempDir: string | undefined;
const commit = arg('--commit') ?? OFL_COMMIT;
if (!dir) {
  tempDir = mkdtempSync(join(tmpdir(), 'ofl-'));
  dir = tempDir;
  console.log(`Fetching OFL ${commit.slice(0, 12)} …`);
  git(dir, 'init', '-q');
  git(dir, 'remote', 'add', 'origin', OFL_REPO);
  git(dir, 'sparse-checkout', 'set', '--no-cone', '/fixtures/', '/LICENSE');
  git(dir, 'fetch', '-q', '--depth', '1', '--filter=blob:none', 'origin', commit);
  git(dir, 'checkout', '-q', 'FETCH_HEAD');
}

try {
  const head = git(dir, 'rev-parse', 'HEAD');
  if (!arg('--source') && head !== commit) throw new Error(`checked out ${head}, expected ${commit}`);
  const date = git(dir, 'log', '-1', '--format=%cs');
  const license = readFileSync(join(dir, 'LICENSE'), 'utf8');
  if (!/MIT License/.test(license)) throw new Error('OFL LICENSE is not MIT – stop and check');

  const fixturesDir = join(dir, 'fixtures');
  const { $schema: _, ...manufacturers } = JSON.parse(readFileSync(join(fixturesDir, 'manufacturers.json'), 'utf8'));
  const files: { manufacturer: string; key: string; json: OflFixture | OflRedirect }[] = [];
  for (const m of readdirSync(fixturesDir, { withFileTypes: true })) {
    if (!m.isDirectory()) continue;
    for (const f of readdirSync(join(fixturesDir, m.name))) {
      if (!f.endsWith('.json')) continue;
      files.push({ manufacturer: m.name, key: f.slice(0, -5), json: JSON.parse(readFileSync(join(fixturesDir, m.name, f), 'utf8')) });
    }
  }

  const db = buildDatabase({
    source: {
      name: 'Open Fixture Library',
      url: 'https://open-fixture-library.org',
      repository: 'https://github.com/OpenLightingProject/open-fixture-library',
      commit: head,
      date,
      license: 'MIT',
    },
    manufacturers,
    files,
  });

  // One fixture per line: readable diffs when the OFL version is updated.
  const lines = [
    '{',
    `"format":${db.format},`,
    `"source":${JSON.stringify(db.source)},`,
    `"manufacturers":${JSON.stringify(db.manufacturers)},`,
    `"channels":${JSON.stringify(db.channels)},`,
    '"fixtures":[',
    db.fixtures.map((f) => JSON.stringify(f)).join(',\n'),
    ']}',
    '',
  ];
  writeFileSync(OUT, lines.join('\n'));

  // MIT requires shipping the licence text with the data.
  mkdirSync(dirname(LICENSE_OUT), { recursive: true });
  writeFileSync(LICENSE_OUT, `Gerätedatenbank in AV Tools: Open Fixture Library, ${db.source.repository} (Commit ${head}, ${date})\n\n${license}`);

  // Small summary for the About page, so it does not have to load the whole database.
  const info = { ...db.source, fixtures: db.fixtures.length, manufacturers: db.manufacturers.length };
  writeFileSync(
    INFO_OUT,
    `// Generated by scripts/ofl-import/import.ts – do not edit.\nexport const FIXTURE_DB_INFO = ${JSON.stringify(info, null, 2)} as const;\n`,
  );

  const modes = db.fixtures.reduce((n, f) => n + f[3].length, 0);
  const size = Buffer.byteLength(lines.join('\n'));
  console.log(
    `${db.fixtures.length} fixtures, ${modes} modes, ${db.manufacturers.length} manufacturers, ` +
      `${db.channels.length} channel names → ${OUT} (${(size / 1024).toFixed(0)} KiB), OFL ${date} ${head.slice(0, 12)}`,
  );
} finally {
  if (tempDir) rmSync(tempDir, { recursive: true, force: true });
}
